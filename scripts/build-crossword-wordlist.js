// Builds netlify/crossword/wordlist.mjs — the answer vocabulary for the
// crossword generator. Run it on a Mac (it needs /usr/share/dict/words);
// the output file is committed, so Netlify never runs this.
//
//   node scripts/build-crossword-wordlist.js
//
// Source: Google's 10,000 most common English words (no-swears list), in
// frequency order. On its own that list is web-crawl English — full of
// brands, place names, people's names and tech jargon (EBAY, MYSQL, DENVER,
// JULIA, SCREENSHOT). We keep only words that are real dictionary words:
// the word itself, or its root (cats → cat, walked → walk, running → run),
// must be a lowercase entry in the system dictionary. That drops ~1,500
// junk entries and leaves ~7,800 everyday-but-varied words.
//
// The generator applies its own blocklist, US-spelling filter and
// 3-letter allowlist on top of this at load time.

const fs = require("fs");
const path = require("path");

const SOURCE_URL =
  "https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa-no-swears.txt";
const DICT = "/usr/share/dict/words";
const OUT = path.join(__dirname, "..", "netlify", "crossword", "wordlist.mjs");
const SKIP_TOP = 100; // the very commonest words (ABOUT, THESE, OTHER) make flat answers

function roots(w) {
  const r = [w];
  const add = (x) => x && x.length >= 2 && r.push(x);
  if (w.endsWith("ies")) add(w.slice(0, -3) + "y");
  if (w.endsWith("es")) add(w.slice(0, -2));
  if (w.endsWith("s")) add(w.slice(0, -1));
  if (w.endsWith("ied")) add(w.slice(0, -3) + "y");
  if (w.endsWith("ed")) {
    add(w.slice(0, -2)); add(w.slice(0, -1));
    if (w.at(-3) === w.at(-4)) add(w.slice(0, -3)); // stopped → stop
  }
  if (w.endsWith("ing")) {
    add(w.slice(0, -3)); add(w.slice(0, -3) + "e");
    if (w.at(-4) === w.at(-5)) add(w.slice(0, -4)); // running → run
  }
  if (w.endsWith("er")) { add(w.slice(0, -2)); add(w.slice(0, -1)); }
  if (w.endsWith("est")) { add(w.slice(0, -3)); add(w.slice(0, -2)); }
  if (w.endsWith("ly")) { add(w.slice(0, -2)); if (w.endsWith("ily")) add(w.slice(0, -3) + "y"); }
  return r;
}

(async () => {
  if (!fs.existsSync(DICT)) throw new Error(`${DICT} not found — run this on macOS or Linux.`);
  // Lowercase entries only: proper nouns are capitalised in the dictionary.
  const dict = new Set(fs.readFileSync(DICT, "utf8").split("\n").filter((w) => /^[a-z]+$/.test(w)));

  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`wordlist fetch failed: ${res.status}`);
  const source = (await res.text()).split("\n").map((w) => w.trim().toLowerCase())
    .filter((w) => /^[a-z]{3,13}$/.test(w));

  const kept = source.slice(SKIP_TOP).filter((w) => roots(w).some((x) => dict.has(x)));
  const body = kept.map((w) => w.toUpperCase()).join(" ");

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT,
    "// Generated by scripts/build-crossword-wordlist.js — do not edit by hand.\n" +
    `// ${kept.length} dictionary-checked words, commonest first.\n` +
    `export default ${JSON.stringify(body)};\n`);
  console.log(`wrote ${kept.length} words (of ${source.length}) to ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e); process.exit(1); });
