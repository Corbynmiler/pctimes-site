// Builds netlify/crossword/wordlist-rich.mjs from scripts/crossword-rich-words.txt
// (the hand-curated "rich" vocabulary; see that file). Run on a Mac:
//
//   node scripts/build-crossword-rich.js
//
// Every word must be in the system dictionary, either as written or as the
// American form of a British spelling (ARMOURY/armory, CALIBRE/caliber,
// IDOLISE/idolize), which catches typos. The output file is committed, so
// Netlify never runs this.

const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "crossword-rich-words.txt");
const OUT = path.join(__dirname, "..", "netlify", "crossword", "wordlist-rich.mjs");
const DICT = "/usr/share/dict/words";

if (!fs.existsSync(DICT)) throw new Error(`${DICT} not found — run this on macOS or Linux.`);
const dict = new Set(fs.readFileSync(DICT, "utf8").split("\n").filter((w) => /^[a-z]+$/.test(w)));

// The American form(s) of a British spelling, to look up in a US dictionary.
function variants(w) {
  const v = [w];
  if (/our/.test(w)) v.push(w.replace(/our/g, "or"));
  if (/re$/.test(w)) v.push(w.replace(/re$/, "er"));
  if (/is(e|ed|es|ing)$/.test(w)) v.push(w.replace(/is(e|ed|es|ing)$/, "iz$1"));
  if (/yse$/.test(w)) v.push(w.replace(/yse$/, "yze"));
  if (/ogue$/.test(w)) v.push(w.replace(/ogue$/, "og"));
  if (/lled|lling|ller/.test(w)) v.push(w.replace(/ll(ed|ing|er)/, "l$1"));
  if (/ae|oe/.test(w)) v.push(w.replace(/ae|oe/g, "e"));
  if (w === "lasagne") v.push("lasagna");
  if (w === "liquorice") v.push("licorice");
  if (w === "mollusc") v.push("mollusk");
  if (w === "sceptic") v.push("skeptic");
  if (w === "gumboot") v.push("gum", "boot");
  return v;
}
// Real words the old system dictionary lacks (newer loanwords, British
// forms, inflections), each checked by hand.
const REVIEWED = new Set(("zap fauna fjord haiku idyll moult pasta penne ramen rumba salsa lasagne " +
  "mislaid odyssey origami parched pavlova appetiser croissant enchanted estranged shambolic triathlon").split(" "));
// Compounds and newer words a 1934 dictionary lacks: accept if both halves are words.
function compound(w) {
  for (let i = 3; i <= w.length - 3; i++) if (dict.has(w.slice(0, i)) && dict.has(w.slice(i))) return true;
  return false;
}

const words = fs.readFileSync(SRC, "utf8").split("\n")
  .filter((l) => !l.trim().startsWith("#"))
  .join(" ").split(/\s+/).map((w) => w.trim().toLowerCase()).filter(Boolean);
const seen = new Set();
const kept = [], rejected = [], viaCompound = [];
for (const w of words) {
  if (seen.has(w)) continue;
  seen.add(w);
  if (!/^[a-z]{3,13}$/.test(w)) { rejected.push(w); continue; }
  if (REVIEWED.has(w) || variants(w).some((x) => dict.has(x))) kept.push(w);
  else if (compound(w)) { kept.push(w); viaCompound.push(w); }
  else rejected.push(w);
}
fs.writeFileSync(OUT,
  "// Generated by scripts/build-crossword-rich.js from scripts/crossword-rich-words.txt — do not edit by hand.\n" +
  `// ${kept.length} hand-picked words readers know but rarely use (QUALM, TENET, BRUSQUE).\n` +
  `export default ${JSON.stringify(kept.map((w) => w.toUpperCase()).join(" "))};\n`);
console.log(`wrote ${kept.length} words to ${path.relative(process.cwd(), OUT)}`);
if (viaCompound.length) console.log(`accepted as compounds (${viaCompound.length}): ${viaCompound.join(" ")}`);
if (rejected.length) { console.log(`NOT in the dictionary (${rejected.length}): ${rejected.join(" ")}`); process.exitCode = 1; }
